"""레벨별 대화 지침.

`{level}` 을 프롬프트에 끼워 넣기만 하고, 길이 규칙은 **모든 레벨에서 8단어**로
고정돼 있었다. A1 에게 맞춘 값이라 B1 학습자에게는 대화가 통째로 짧게 느껴진다 —
상대가 세 마디로 끊어 말하면 연습할 거리가 안 생긴다.

교정 강도(strictness.py)와 같은 방식으로 조각을 갈아 끼운다. 레벨은 두 가지를
동시에 정한다:

  1. AI 가 얼마나 길게 말하는가 (연습 상대의 수준)
  2. 학습자에게 주는 say_en 이 얼마나 긴가 (따라 말할 것의 수준)

둘이 따로 놀면 안 된다. 8단어짜리 상대에게 20단어짜리 답을 주라고 할 수는 없다.
"""

from __future__ import annotations

from typing import Literal

Level = Literal["A1", "A2", "B1"]

DEFAULT_LEVEL: Level = "A1"

ORDER: tuple[Level, ...] = ("A1", "A2", "B1")

LABELS: dict[Level, str] = {
    "A1": "왕초보",
    "A2": "기초",
    "B1": "조금 익숙",
}

_PROMPTS: dict[Level, str] = {
    "A1": """\
## 이번 세션의 레벨: A1 (완전 초보)

- `reply` 는 **한 문장, 8단어 이내.** 두 문장이 필요하면 둘 다 아주 짧게.
- 기초 어휘만. 관용구·구동사·축약이 겹친 표현은 피하세요.
- 질문은 한 번에 하나만. 두 가지를 같이 물으면 학습자가 어느 쪽에 답할지 모릅니다.
- `say_en` 은 **1~3단어**. 한 단어도 충분한 답입니다.
- `say_more` 는 거기에 한 조각만 더 붙인 정도.\
""",
    "A2": """\
## 이번 세션의 레벨: A2 (기초)

- `reply` 는 **한두 문장, 문장당 12단어 이내.**
- 답만 하지 말고 **한 조각을 더 얹으세요.** 짧은 사실이나 되묻는 질문 하나.
  "Platform nine." 보다 "Platform nine. It leaves in four minutes." 가 낫습니다.
- 자주 쓰는 구동사(pick up, look for)는 괜찮습니다. 드문 관용구는 아직 아닙니다.
- `say_en` 은 **한 문장**. 주어와 동사가 있는 완결된 문장으로 주세요.
- `say_more` 는 이유나 조건을 한 마디 붙인 것.\
""",
    "B1": """\
## 이번 세션의 레벨: B1 (조금 익숙)

이 학습자에게 세 마디로 끊어 말하면 연습이 안 됩니다. **대화를 밀고 나가세요.**

- `reply` 는 **두세 문장, 문장당 18단어 이내.** 짧게 끊지 마세요.
- 매 턴 **대화를 이어갈 것을 하나 넣으세요** — 되묻기, 이유 묻기, 선택지 제시,
  가벼운 의견 중 하나. 학습자가 "네/아니오"로 끝낼 수 있는 턴을 만들지 마세요.
- 캐릭터에 어울리는 구체적인 정보를 자연스럽게 덧붙이세요(가격, 시간, 조건, 대안).
  역할을 벗어나 지어내라는 뜻이 아니라, 실제 그 사람이 알 법한 것을 말하라는 뜻입니다.
- `say_en` 은 **완결된 한 문장**, `say_more` 는 이유나 조건이 붙은 두 문장까지.
  여전히 학습자가 **그대로 말할 수 있어야** 합니다 — 템플릿이나 빈칸은 안 됩니다.
- 길게 말하라는 건 **영어 필드에만** 해당합니다. `note`·`hint_ko`·`reply_ko` 는
  이 레벨에서도 한국어입니다. 설명이 길어져도 언어는 바뀌지 않습니다.\
""",
}


# 학습자가 **따라 말할** 영어 필드의 하드캡. 레벨마다 다르다.
#
# 왜 레벨마다 다른가
# ------------------
# B1 프롬프트는 `say_more` 를 "이유나 조건이 붙은 두 문장까지" 라고 시키는데
# 하드캡은 A1 기준인 10단어에 고정돼 있었다. 두 문장이 10단어에 들어갈 리 없다 —
# **프롬프트가 시킨 것을 스키마가 거부**하고 있었고, 그때마다 재시도가 돌아
# 지연이 두 배가 됐다. B1 측정에서 84회 중 3회가 이것이었다.
#
# 값은 프롬프트 목표보다 넉넉하게 둔다(require_english 의 규칙). 목표와 하드캡이
# 같으면 정상 출력이 걸린다. 캡은 문체를 강제하는 자가 아니라 폭주를 막는 울타리다.
SAY_LIMITS: dict[Level, dict[str, tuple[int, int]]] = {
    #            say_en (단어, 글자)    say_more (단어, 글자)
    "A1": {"say_en": (5, 32), "say_more": (10, 64)},
    "A2": {"say_en": (10, 64), "say_more": (18, 110)},
    "B1": {"say_en": (14, 90), "say_more": (28, 180)},
}

# 레벨을 모를 때 쓰는 값. **가장 느슨한 쪽**이다 — 문맥이 없다는 이유로 정상 출력을
# 거부해 재시도를 만들면 안 된다. 레벨별 조임은 레벨을 아는 곳에서만 적용한다.
LOOSEST_SAY_LIMITS: dict[str, tuple[int, int]] = SAY_LIMITS["B1"]


def say_limits(level: str | None, field: str) -> tuple[int, int]:
    """이 레벨에서 `field` 가 가질 수 있는 (최대 단어, 최대 글자)."""
    return SAY_LIMITS.get(level or "", LOOSEST_SAY_LIMITS)[field]


def prompt_for(level: str) -> str:
    return _PROMPTS.get(level, _PROMPTS[DEFAULT_LEVEL])
